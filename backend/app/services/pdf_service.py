class NumberedCanvas(canvas.Canvas):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748B"))
        
        # Header (pages > 1)
        if self._pageNumber > 1:
            self.drawString(54, 750, "Smart Multi-Agent AI Code Reviewer v2.0 - Automated Review Report")
            self.setStrokeColor(colors.HexColor("#E2E8F0"))
            self.setLineWidth(0.5)
            self.line(54, 744, 558, 744)

        # Footer (all pages)
        page_text = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(558, 36, page_text)
        self.drawString(54, 36, "Confidential - Generated by Smart Multi-Agent AI Review System")
        self.setStrokeColor(colors.HexColor("#E2E8F0"))
        self.setLineWidth(0.5)
        self.line(54, 48, 558, 48)
        self.restoreState()

class PDFReportService:
    @staticmethod
    def _create_agent_chart(scores: Dict[str, int]) -> bytes:
        plt.figure(figsize=(6.5, 2.8), dpi=200)
        agents = ["Security", "Quality", "Performance", "Testing", "Maintainability"]
        vals = [
            scores.get("security", 0),
            scores.get("code_quality", 0),
            scores.get("performance", 0),
            scores.get("testing", 0),
            scores.get("maintainability", 0)
        ]
        bar_colors = ["#10B981" if v >= 80 else "#F59E0B" if v >= 60 else "#EF4444" for v in vals]
        
        bars = plt.bar(agents, vals, color=bar_colors, width=0.55, edgecolor="#0F172A", linewidth=0.8)
        plt.title("Agent Performance Scores (0 - 100)", fontsize=11, fontweight="bold", pad=10, color="#1E293B")
        plt.ylim(0, 110)
        plt.grid(axis="y", linestyle="--", alpha=0.4)
        plt.gca().set_axisbelow(True)
        
        for bar in bars:
            h = bar.get_height()
            plt.text(bar.get_x() + bar.get_width()/2., h + 2, f"{int(h)}%", ha="center", va="bottom", fontsize=9, fontweight="bold", color="#1E293B")

        plt.tight_layout()
        buf = io.BytesIO()
        plt.savefig(buf, format="png", bbox_inches="tight")
        plt.close()
        buf.seek(0)
        return buf.getvalue()

