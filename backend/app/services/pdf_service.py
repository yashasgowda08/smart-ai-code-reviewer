    @staticmethod
    def _create_consensus_chart(local_score: int, groq_score: Optional[int]) -> bytes:
        plt.figure(figsize=(5.0, 2.6), dpi=200)
        labels = ["Local Multi-Agent", "External Groq AI"]
        vals = [local_score, groq_score if groq_score is not None else 0]
        colors_list = ["#3B82F6", "#8B5CF6"]

        bars = plt.bar(labels, vals, color=colors_list, width=0.45, edgecolor="#0F172A", linewidth=0.8)
        plt.title("Local Multi-Agent vs. External Groq AI Score", fontsize=10, fontweight="bold", pad=10, color="#1E293B")
        plt.ylim(0, 110)
        plt.grid(axis="y", linestyle="--", alpha=0.4)
        plt.gca().set_axisbelow(True)

        for bar in bars:
            h = bar.get_height()
            if h > 0:
                plt.text(bar.get_x() + bar.get_width()/2., h + 2, f"{int(h)}/100", ha="center", va="bottom", fontsize=9, fontweight="bold", color="#1E293B")
            else:
                plt.text(bar.get_x() + bar.get_width()/2., 10, "N/A", ha="center", va="bottom", fontsize=9, fontweight="bold", color="#64748B")

        plt.tight_layout()
        buf = io.BytesIO()
        plt.savefig(buf, format="png", bbox_inches="tight")
        plt.close()
        buf.seek(0)
        return buf.getvalue()

